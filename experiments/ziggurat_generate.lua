-- Solve Doornik's equal-area recurrence with MPFR, not host libm doubles.
package.path = "experiments/?.lua;" .. package.path
local m = require("mpfr")
m.precision = tonumber(arg[1]) or 256
local zero, one, two = m.new(0), m.new(1), m.new(2)
local pi = m.new(); m.c.mpfr_const_pi(pi, 0)
local sqrt_two, sqrt_half_pi = m.sqrt(two), m.sqrt(m.div(pi, two))
local function pdf(x) return m.exp(m.div(m.sub(zero, m.mul(x, x)), two)) end
local function geometry(r)
	local fr = pdf(r)
	local v = m.add(m.mul(r, fr), m.mul(sqrt_half_pi, m.erfc(m.div(r, sqrt_two))))
	local xs, ys = {[1] = r}, {[1] = fr}
	for i = 2, 255 do
		local f = m.add(ys[i - 1], m.div(v, xs[i - 1]))
		if m.cmp(f, one) >= 0 then return nil end
		xs[i], ys[i] = m.sqrt(m.mul(m.new(-2), m.log(f))), f
	end
	local residual = m.sub(m.mul(xs[255], m.sub(one, ys[255])), v)
	xs[0], ys[0], xs[256], ys[256] = m.div(v, fr), zero, zero, one
	return residual, xs, ys
end
local lo, hi = m.new("3.6"), m.new("3.7")
for _ = 1, m.precision - 24 do
	local mid = m.div(m.add(lo, hi), two)
	local residual = geometry(mid)
	if not residual or m.cmp(residual, zero) < 0 then lo = mid else hi = mid end
end
local _, xs, ys = geometry(hi)
assert(xs, "root must have all 256 strips")
-- One MPFR construction emits exact integer literals for every implementation.
-- No generated table passes through a host floating-point number.
local format = arg[2] or "experiment"
local formats = {
	experiment = {'//! Generated by experiments/ziggurat_generate.lua with MPFR; no production sampler uses this table.\nconst Fixed = @import("fixed").Fixed;\npub const Strip = struct { x: Fixed, y: Fixed, k: u64 };\npub const strips = [_]Strip{\n', '\t.{ .x = .{ .m = %s, .e = %d }, .y = .{ .m = %s, .e = %d }, .k = %s },\n', '};\n'},
	zig = {'//! Generated by experiments/ziggurat_generate.lua with MPFR; 256 fixed-point strips.\nconst Fixed = @import("fixed").Fixed;\npub const Strip = struct { x: Fixed, y: Fixed, k: u64 };\npub const strips = [_]Strip{\n', '\t.{ .x = .{ .m = %s, .e = %d }, .y = .{ .m = %s, .e = %d }, .k = %s },\n', '};\n'},
	lua = {'-- Generated by experiments/ziggurat_generate.lua with MPFR; exact cdata mantissas.\nreturn {\n', '\t{%sLL, %d, %sLL, %d, %sULL},\n', '}\n'},
	rust = {'//! Generated by experiments/ziggurat_generate.lua with MPFR.\nuse super::Fixed;\npub(crate) struct Strip { pub x: Fixed, pub y: Fixed, pub k: u64 }\npub(crate) const STRIPS: [Strip; 256] = [\n', '\tStrip { x: Fixed { m: %s, e: %d }, y: Fixed { m: %s, e: %d }, k: %s },\n', '];\n'},
	lean = {'-- Generated by experiments/ziggurat_generate.lua with MPFR.\nimport Randoml.Fixed\nnamespace Randoml.Ziggurat\nstructure Strip where\n  x : Fixed.Value\n  y : Fixed.Value\n  k : Nat\ndef strips : Array Strip := #[\n', '  { x := { m := %s, e := %d }, y := { m := %s, e := %d }, k := %s },\n', ']\nend Randoml.Ziggurat\n'},
	roc = {'# Generated by experiments/ziggurat_generate.lua with MPFR.\nZigguratTables :: [].{\n\tstrips : List((I64, I32, I64, I32, U64))\n\tstrips = [\n', '\t\t(%s, %d, %s, %d, %s),\n', '\t]\n}\n'},
}
local selected = assert(formats[format], "unknown table format")
io.write(selected[1])
for i = 0, 255 do
	local xm, xe = m.pair(xs[i]); local ym, ye = m.pair(ys[i])
	-- Thresholds use the stored widths, so fixed truncation cannot enlarge
	-- the conservative rectangle relative to the adjacent stored strip.
	local next_m, next_e = m.pair(xs[i + 1])
	local ratio = m.div(m.fixed(next_m, next_e), m.fixed(xm, xe))
	local k = m.text(m.floor(m.shift(ratio, 55)))
	io.write(selected[2]:format(xm, xe, ym, ye, k))
end
io.write(selected[3])
